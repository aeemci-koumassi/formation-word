CREATE TABLE IF NOT EXISTS public.recensement_emsp (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    matricule TEXT UNIQUE NOT NULL,
    nom TEXT NOT NULL,
    genre TEXT NOT NULL, -- 'Frère' ou 'Sœur'
    nationalite TEXT DEFAULT 'Côte d''Ivoire',
    date_naissance DATE,
    whatsapp TEXT NOT NULL,
    telephone_urgence TEXT,
    email TEXT,
    statut TEXT NOT NULL, -- 'Étudiant(e) régulier(e)', 'Auditeur libre', 'Stagiaire', 'Personnel', 'Alumni'
    cycle TEXT NOT NULL, -- 'Licence Professionnelle (Bac +3)', 'Master Professionnel (Bac +5)', 'Mastère Spécialisé', 'FSP'
    filiere TEXT NOT NULL, -- 'Logistique et Numérique', 'Finance Digitale', 'Marketing Digital', 'DSER/TNOR', 'Régulation', 'APSF/IPSF/CPSF'
    niveau TEXT NOT NULL, -- 'L1', 'L2', 'L3', 'M1', 'M2', 'MS', 'FSP 1', 'FSP 2', 'Cadre'
    residence TEXT NOT NULL, -- 'Campus EMSP (Cité)', 'Hors Campus (Abidjan)'
    precision_residence TEXT, -- Chambre campus ou Commune/Quartier (Treichville, Marcory, Koumassi...)
    commissions TEXT[], -- ['Prédication & Dawa', 'Communication', 'Organisation', ...]
    competences TEXT, -- Graphisme, Web, Prise de parole, etc.
    remarques TEXT,
    statut_validation TEXT DEFAULT 'Validé'
);

-- Activation de Row Level Security (RLS)
ALTER TABLE public.recensement_emsp ENABLE ROW LEVEL SECURITY;

-- Politiques d'accès publiques (Anonyme peut lire, s'enregistrer et modifier)
CREATE POLICY "Lecture publique pour les membres et le bureau"
ON public.recensement_emsp
FOR SELECT
TO public
USING (true);

CREATE POLICY "Enregistrement public pour le recensement"
ON public.recensement_emsp
FOR INSERT
TO public
WITH CHECK (true);

CREATE POLICY "Mise à jour autorisée pour le bureau"
ON public.recensement_emsp
FOR UPDATE
TO public
USING (true);

CREATE POLICY "Suppression autorisée pour le bureau"
ON public.recensement_emsp
FOR DELETE
TO public
USING (true);

-- Index de performance pour les recherches et filtres
CREATE INDEX IF NOT EXISTS idx_emsp_matricule ON public.recensement_emsp(matricule);
CREATE INDEX IF NOT EXISTS idx_emsp_whatsapp ON public.recensement_emsp(whatsapp);
CREATE INDEX IF NOT EXISTS idx_emsp_genre ON public.recensement_emsp(genre);
CREATE INDEX IF NOT EXISTS idx_emsp_filiere ON public.recensement_emsp(filiere);
CREATE INDEX IF NOT EXISTS idx_emsp_residence ON public.recensement_emsp(residence);
